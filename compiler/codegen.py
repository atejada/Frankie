    def gen_hash_destruct_assign(self, node: HashDestructAssign):
        """{name, age} = user  →  name = user.get('name'); age = user.get('age')"""
        val_tmp = self.temp_var("_hd")
        value = self.gen_expr(node.value)
        self.emit(f"{val_tmp} = {value}")
        for key in node.keys:
            self.emit(f"{key} = ({val_tmp}.get({key!r}) if isinstance({val_tmp}, dict) else None)")

    def gen_lambda(self, node: 'LambdaLiteral') -> str:
        """Generate a Python lambda or named inner function for a Frankie lambda literal.
        Single-expression bodies become Python lambdas.
        Multi-statement bodies emit a named helper function and return its reference.
        """
        param_parts = []
        for i, pname in enumerate(node.params):
            default = node.defaults[i] if i < len(node.defaults) else None
            if default is not None:
                param_parts.append(f"{pname}={self.gen_expr(default)}")
            else:
                param_parts.append(pname)
        params_str = ", ".join(param_parts)

        if len(node.body) == 1 and not isinstance(node.body[0], (
                FuncDef, IfStmt, UnlessStmt, WhileStmt, UntilStmt,
                DoWhileStmt, ForInStmt, BeginRescue, CaseStmt,
                PrintStmt, DebugPrint, ReturnStmt, RaiseStmt, IndexAssign, IndexCompoundAssign, CompoundAssign, OrAssign, DestructAssign, HashDestructAssign, ConstAssign, PostfixIf)):
            # Single-expression body → compact lambda
            body_expr = self.gen_expr(node.body[0])
            return f"(lambda {params_str}: {body_expr})"

        # Multi-statement body → named inner function
        fn_name = self.temp_var("_lambda")
        self.emit(f"def {fn_name}({params_str}):")
        self.indent()
        for stmt in node.body[:-1]:
            self.gen_stmt(stmt)
        last = node.body[-1]
        if isinstance(last, ReturnStmt):
            self.gen_stmt(last)
        elif isinstance(last, (FuncDef, IfStmt, UnlessStmt, WhileStmt, UntilStmt,
                                DoWhileStmt, ForInStmt, BeginRescue, CaseStmt,
                                PrintStmt, DebugPrint, RaiseStmt)):
            self.gen_stmt(last)
        else:
            last_expr = self.gen_expr(last)
            self.emit(f"return {last_expr}")
        self.dedent()
        return fn_name

