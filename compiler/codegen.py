    def gen_begin_rescue(self, node):
        self.emit("try:")
        self.indent()
        self.gen_body(node.body)
        self.dedent()
        clauses = node.rescue_clauses
        for i, clause in enumerate(clauses):
            if clause.error_type is None:
                exc_class = 'Exception'
            else:
                # v1.17: resolved at runtime so user-defined error types
                # (error TimeoutError) take precedence over builtins
                exc_class = f"_fk_exc({clause.error_type!r})"
            tmp = clause.rescue_var or '_fk_err'
            self.emit(f"except {exc_class} as {tmp}:")
            self.indent()
            if clause.body:
                if clause.rescue_var:
                    self.emit(f"{clause.rescue_var} = str({clause.rescue_var})")
                self.gen_body(clause.body)
            else:
                self.emit("pass")
            self.dedent()
        if node.ensure_body:
            self.emit("finally:")
            self.indent()
            self.gen_body(node.ensure_body)
            self.dedent()

    def gen_raise(self, node):
        # v1.17: typed raise — raise TimeoutError, "msg"
        if getattr(node, 'error_type', None):
            if node.message is not None:
                msg = self.gen_expr(node.message)
                self.emit(f"raise _fk_make_error({node.error_type!r}, _fk_to_str({msg}))")
            else:
                self.emit(f"raise _fk_make_error({node.error_type!r}, {node.error_type!r})")
        elif node.message:
            msg = self.gen_expr(node.message)
            self.emit(f"raise RuntimeError(_fk_to_str({msg}))")
        else:
            self.emit("raise")

    def gen_error_def(self, node: 'ErrorDef'):
        """error TimeoutError  →  TimeoutError = _fk_def_error('TimeoutError')"""
        self.emit(f"{node.name} = _fk_def_error({node.name!r})")

    def gen_enum_def(self, node: 'EnumDef'):
        """enum Status(pending, active)  →  Status = _fk_def_enum('Status', [...])"""
        members = ", ".join(repr(m) for m in node.members)
        self.emit(f"{node.name} = _fk_def_enum({node.name!r}, [{members}])")

    def gen_import(self, node: 'ImportStmt'):
        """import "lib/math" as math  →  math = _fk_import("lib/math")"""
        path = self.gen_expr(node.path)
        alias = node.alias
        if alias is None:
            # Default alias: basename without extension ("lib/math" → math)
            if isinstance(node.path, StringLiteral) and node.path.parts:
                raw = "".join(v for k, v in node.path.parts if k == 'literal')
                alias = raw.replace('\\', '/').rsplit('/', 1)[-1]
                alias = alias[:-3] if alias.endswith('.fk') else alias
            else:
                raise CodeGenError("import: 'as' alias required for non-literal paths")
        self.emit(f"{_py_safe(alias)} = _fk_import({path})")

    def gen_require(self, node):
        path = self.gen_expr(node.path)
        self.emit(f"_fk_require({path})")

    def gen_stitch(self, node):
        name = self.gen_expr(node.name)
        self.emit(f"_fk_stitch({name})")

    def gen_case(self, node):
        if node.subject is not None:
            subj = self.gen_expr(node.subject)
            subj_tmp = self.temp_var("_case")
            self.emit(f"{subj_tmp} = {subj}")
        first = True
        for values, body in node.when_clauses:
            if node.subject is not None:
                cond = " or ".join(self._case_cond(subj_tmp, v) for v in values)
            else:
                # bare case: when condition (truthy)
                cond_parts = [self.gen_expr(v) for v in values]
                cond = " or ".join(cond_parts)
            kw = "if" if first else "elif"
            self.emit(f"{kw} {cond}:")
            self.indent()
            self.gen_body(body)
            self.dedent()
            first = False
        if node.else_body is not None:
            self.emit("else:")
            self.indent()
            self.gen_body(node.else_body)
            self.dedent()

    def gen_destruct_assign(self, node):
        value = self.gen_expr(node.value)
        if node.splat_index >= 0:
            n_before = node.splat_index
            n_after  = len(node.names) - node.splat_index - 1
            names    = ", ".join(node.names)
            self.emit(f"{names} = _fk_unpack_splat({value}, {n_before}, {n_after})")
        else:
            names = ", ".join(node.names)
            self.emit(f"{names} = _fk_unpack({value}, {len(node.names)})")

    def gen_record_def(self, node: RecordDef):
        """Generate a record type — a constructor function + hash-based instances.

        record Point(x, y)  generates:
          def Point(x, y):
              return {"__type__": "Point", "x": x, "y": y}

        Plus a structural equality helper and pretty __repr__ in _fk_to_str (handled by
        the existing hash-printing path — __type__ is displayed as the record name).
        """
        fields = node.fields
        params = ", ".join(fields)
        # Constructor
        self.emit(f"def {node.name}({params}):")
        self.indent()
        pairs = ", ".join(f'"{f}": {f}' for f in fields)
        self.emit(f'return {{"__type__": "{node.name}", {pairs}}}')
        self.dedent()
        self.emit()

